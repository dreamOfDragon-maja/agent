def render(product: dict) -> str:
    category_label = CATEGORY_LABELS[product["category"]]
    items = "\n".join(f"- {item}" for item in product["items"])
    faq = "\n".join(f"- {item}" for item in product["faq"])
    min_price, max_price = product["price"]
    return f"""# {product['name']} 使用说明书

## 商品概述
{product['overview']}

- 品牌：{product['brand']}
- 分类：{category_label}
- 适用人群：{product['target']}
- 参考价格：¥{min_price} - ¥{max_price}

## 包装清单
- 商品主体 × 1
- 说明书 × 1
- 保修卡 × 1
{items}

## 使用说明
{product['usage']}

## 保养与注意事项
{product['care']}

## 保修政策
{product['warranty']}

## 退换货政策
{product['return_policy']}

## 常见问题
{faq}
"""


def main() -> None:
    KB_DIR.mkdir(parents=True, exist_ok=True)
    for product in PRODUCTS:
        path = KB_DIR / product["doc"]
        path.write_text(render(product), encoding="utf-8")
        print(f"generated: {path.name}")


if __name__ == "__main__":
    main()
